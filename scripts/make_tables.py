def _write(path: str, lines: list[str]) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {path}")


def main() -> int:
    p = argparse.ArgumentParser(description="Emit paper LaTeX tables from aggregate CSVs.")
    p.add_argument("--public_dir", default=os.path.join(_ROOT, "results", "public"))
    p.add_argument("--output_dir", default=os.path.join(_ROOT, "paper", "tables"))
    args = p.parse_args()

    targets = [
        ("main_results_with_ci.csv", "main_results.tex", emit_main_results),
        ("ablation_results_with_ci.csv", "ablation_results.tex", emit_ablation_results),
        ("model_generalization_with_ci.csv", "model_generalization.tex", emit_model_generalization),
        ("benchmark_generalization_with_ci.csv", "benchmark_generalization.tex", emit_benchmark_generalization),
        ("judge_agreement.csv", "judge_agreement.tex", emit_judge_agreement),
        ("category_results.csv", "category_results.tex", emit_category_results),
        ("query_budget_analysis.csv", "query_efficiency.tex", emit_query_efficiency),
        ("hard_subset_analysis.csv", "hard_subset.tex", emit_hard_subset),
        ("optimizer_baselines.csv", "optimizer_comparison.tex", emit_optimizer_comparison),
        ("ablation_results_with_ci.csv", "full_matrix.tex", emit_full_matrix),
    ]
    n_written = 0
    for src, dst, emit_fn in targets:
        src_path = os.path.join(args.public_dir, src)
        rows = _read_csv(src_path)
        if not rows:
            print(f"[skip] {src} (missing or empty)")
            continue
        emit_fn(rows, os.path.join(args.output_dir, dst))
        n_written += 1
    if n_written == 0:
        print("No tables emitted. Run aggregate_results.py and "
              "compute_confidence_intervals.py first.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
